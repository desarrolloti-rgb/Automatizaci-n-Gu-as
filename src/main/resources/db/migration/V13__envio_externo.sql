-- El seguimiento de una guia que lleva un transportista externo (SAMEX): lo que el lector de su
-- portal encontro al buscarla por el folio. Una fila por guia, porque un envio es una guia y una
-- guia es un envio. Se crea en la primera busqueda y se actualiza en cada una, tambien cuando el
-- transportista todavia no tiene el envio (NO_ENCONTRADO): asi se sabe desde cuando se la busca.
CREATE TABLE envio_externo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    guia_id           BIGINT                   NOT NULL,
    transportista     VARCHAR(50)              NOT NULL,
    -- El folio que se busco, copiado de la guia: es lo que se comparo con las referencias.
    folio             BIGINT                   NOT NULL,
    -- El numero de envio del transportista. NULL mientras no haya uno confirmado.
    numero            VARCHAR(30),
    -- ASOCIADO, NO_ENCONTRADO o CONFLICTO. VARCHAR y no entero, como estado en guia.
    resultado         VARCHAR(20)              NOT NULL,
    -- Por que no quedo asociado: es lo que ve bodega.
    motivo            VARCHAR(500),
    -- Lo que dice el portal, tal cual ("Entregada movilidad 23/11/2026").
    estado_portal     VARCHAR(200),
    -- Las referencias del envio en el portal, separadas por coma. Entre ellas esta el folio.
    referencias       VARCHAR(500),
    -- Cuando lo entrego el transportista. NULL mientras no lo entregue.
    fecha_entrega     TIMESTAMP WITH TIME ZONE,
    -- El PDF de la entrega, cuando ya se bajo. El hash es SHA-256, como el de las fotos.
    evidencia_url     VARCHAR(500),
    evidencia_hash    VARCHAR(64),
    primera_busqueda  TIMESTAMP WITH TIME ZONE NOT NULL,
    ultima_busqueda   TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_envio_externo         PRIMARY KEY (id),
    CONSTRAINT uq_envio_externo_guia    UNIQUE (guia_id),
    -- Un mismo envio no puede quedar en dos guias. Los NULL no chocan entre si.
    CONSTRAINT uq_envio_externo_numero  UNIQUE (transportista, numero),
    CONSTRAINT fk_envio_externo_guia    FOREIGN KEY (guia_id) REFERENCES guia (id)
);
